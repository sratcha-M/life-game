const CARD_CHANCE = 0.18

function card(id: string, age: number, bg: BgId, cast: CharId[], line: Line | string, choices: Choice[], extra: Partial<Scene> = {}): Scene {
  return {
    id: 'ev_' + id, age, bg, cast, chance: CARD_CHANCE,
    lines: [typeof line === 'string' ? { text: line } : line],
    choices, ...extra,
  }
}
