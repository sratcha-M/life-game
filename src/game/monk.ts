export const monkAllows = (id: string) => id.startsWith('monk_') || id.startsWith('job_monk_') || id.startsWith('long_') ||MONK_OK.some((k) => idIs(id, k))

/** ทางเลือกที่ผิดศีล/วินัย → ซ่อนเมื่อเป็นนักบวช */
const BAN: Record<string, (c: Choice, s: GameState) => boolean> = {
  f_bill: (c) => /กู้เงิน|แฟน/.test(c.text), // นักบวชไม่ก่อหนี้ และไม่มีแฟน
  secret01: (c) => c.text.includes('ทำงาน'),
  mom_pass: (c, s) => boy(s) && c.text.includes('กุมมือ'), // พระถูกต้องตัวสตรีไม่ได้ แม้เป็นแม่
  dadsick: (c) => /ย้ายกลับบ้าน|จ้างคน/.test(c.text),
  nong_care: (c) => c.text.includes('รับแม่มาอยู่'),
  th_ton2: (c) => c.text.includes('ฉลอง'), // ไปร้านเหล้า
  x_tonjay: (c) => c.text.includes('ดื่ม'),
  tonreturn: (c) => c.text.includes('หุ้นส่วน'),
  jay_sorry: (c) => c.text.includes('ส่วนแบ่ง'),
  genie: (c) => c.text.includes('รวย'),
  callcenter: (c) => c.text.includes('ลูกหลาน'),
  life_volunteer: (c) => c.text.includes('วาดรูป'),
}
export function monkBans(sceneId: string, c: Choice, s: GameState) {
  const k = Object.keys(BAN).find((b) => idIs(sceneId, b))
  return !!k && BAN[k](c, s)
}

