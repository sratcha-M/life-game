export const isMonk = (s: GameState) => s.career === 'monk'
const boy = (s: GameState) => s.gender === 'boy'
const R = (text: string): Line[] => [{ text }]
const G = (s: GameState, monk: string, nun: string) => (boy(s) ? monk : nun)
const idIs = (id: string, k: string) => id === k || new RegExp(`^${k}_\\d+$`).test(id)

/** ฉากชีวิตทั่วไปที่ยังเข้ากับชีวิตนักบวช (id ตรง หรือ id_อายุ) */
